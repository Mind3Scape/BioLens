const norm = (s) => (s || '').toString().toLowerCase()
  .replace(/\u0451/g, 'е')
  .replace(/[.,()\[\]{}\/\\:;+*"'\u00ab\u00bb]/g, ' ')
  .replace(/[-\u2013\u2014]/g, ' ')
  .replace(/\s+/g, ' ')
  .trim();

/* Слова, которые МЕНЯЮТ смысл показателя. Если такое слово есть в названии из бланка,
   а в синониме ни одного слова из той же семьи нет — это другой показатель,
   и склеивать их нельзя. Из-за этого раньше «Холестерин не-ЛПВП» попадал в ЛПВП,
   «гликированный гемоглобин» — в обычный гемоглобин, а «средняя концентрация
   гемоглобина в эритроците» — снова в гемоглобин.

   Семья, а не плоский список: «анти» и «антитела» — одно и то же уточнение,
   и синониму достаточно любого слова из семьи. Звёздочка на конце — «сравнивать
   по началу слова», чтобы падежи не мешали; без звёздочки слово должно совпасть
   целиком (иначе «анти» цепляло бы «антиген» в названии ПСА). */
