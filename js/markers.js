const words = (s) => norm(s).split(' ').filter(Boolean);
const hasWord = (list, stem) => stem.endsWith('*')
  ? list.some(w => w.startsWith(stem.slice(0, -1)))
  : list.includes(stem);

/* Ищем канонический ключ по названию из бланка.
   Порядок строгий: точное совпадение названия → однозначный код (MCV, ТТГ, МСНС)
   → самый длинный синоним, все слова которого есть в названии. */
export function matchMarker(rawName) {
  const n = norm(rawName);
  if (!n) return null;
  const nWords = words(rawName);

  for (const [key, m] of Object.entries(MARKERS)) {
    for (const syn of m.syn) if (norm(syn.replace(/^=/, '')) === n) return { key, exact: true };
  }

  // какие уточнения стоят в названии из бланка
  const nFamilies = MODIFIER_FAMILIES.filter(fam => fam.w.some(stem => hasWord(nWords, stem)));

  // однозначный код показателя — опознаём даже внутри длинного названия
  let byCode = null;
  if (!nFamilies.some(fam => !fam.codeSafe)) {
    for (const [key, m] of Object.entries(MARKERS)) {
      for (const code of (m.codes || [])) {
        if (!nWords.includes(norm(code))) continue;
        if (!byCode || code.length > byCode.len) byCode = { key, len: code.length };
      }
    }
  }
  if (byCode) return { key: byCode.key, exact: false };

  let best = null;
  for (const [key, m] of Object.entries(MARKERS)) {
    for (const syn of m.syn) {
      if (syn.startsWith('=')) continue;      // слишком широкое слово — только точное совпадение
      const sWords = words(syn);
      if (!sWords.length) continue;
      const covered = sWords.every(w => nWords.includes(w) || (w.length >= 5 && nWords.some(x => x.startsWith(w))));
      if (!covered) continue;
      // каждое уточнение из названия должно быть отражено и в синониме
      const missed = nFamilies.some(fam => !fam.w.some(stem => hasWord(sWords, stem)));
      if (missed) continue;
      const score = sWords.join('').length + sWords.length * 2;
      if (!best || score > best.score) best = { key, score };
    }
  }
  return best ? { key: best.key, exact: false } : null;
}

/* Пересчёт значения из единицы бланка в каноническую.
   Если единицу не знаем — оставляем как есть и честно помечаем. */
export function toCanonical(key, value, unitRaw) {
  const m = MARKERS[key];
  const v = Number(value);
  if (!m || !isFinite(v)) return { value: v, unit: unitRaw || '', converted: false, factor: 1 };
  const u = norm(unitRaw).replace(/\s/g, '');
  if (!u) return { value: v, unit: m.unit, converted: false, factor: 1 };
  const table = m.conv || {};
  // у счётных показателей (СОЭ, MCV, коэффициенты) единица одна и переводить нечего —
  // пустая таблица не значит «единица незнакомая»
  if (!Object.keys(table).length) return { value: v, unit: m.unit, converted: false, factor: 1 };
  for (const [k, f] of Object.entries(table)) {
    if (norm(k).replace(/\s/g, '') === u) {
      return { value: +(v * f).toFixed(4), unit: m.unit, converted: f !== 1, factor: f };
    }
  }
  return { value: v, unit: unitRaw, converted: false, factor: 1, unknownUnit: true };
}

